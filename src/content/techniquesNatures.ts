const technique = (d: Def): TechniqueDef => {
  const palier = PALIER_DU_RANG[d.rang] ?? 2;
  const prealable = d.rang === 'S' && PREALABLE_S[d.element];
  return {
    categorie: 'ninjutsu',
    puissance: d.puissance,
    chakra: d.chakra,
    // Une technique défensive ne se lance pas comme une attaque spéciale : on l'oppose à un coup.
    offensive: !d.tactique?.defense,
    requis: [{ maitrise: `nature_${d.element}`, palierMin: palier }, ...(prealable ? [{ maitrise: prealable, palierMin: 3 }] : [])],
    // Un rang S ne s'enseigne pas : on le développe seul·e, au bout d'une technique de rang A maîtrisée.
    enseignee: d.rang === 'S' ? 'partout' : 'village',
    tactique: d.tactique,
  };
};

